"use client";
import { useMemo, useState } from "react";
import { AnimatePresence, motion } from "motion/react";
import { Target, Lightbulb, AlertTriangle, TrendingUp, ChevronRight, ArrowRight, X, Download } from "lucide-react";
import { useStore } from "@/lib/store";
import { getInsights, type InsightAction } from "@/features/insights/insights";
import { getMomentum, STATE_LABEL, type MomentumState } from "@/features/momentum/momentum";

const ICON = { focus: Target, trend: Lightbulb, attention: AlertTriangle, positive: TrendingUp } as const;
const TONE = { focus: "#22B573", trend: "#2F8BFF", attention: "#FF8A3C", positive: "#22B573" } as const;

export default function InsightsPanel({ now, onAction }: { now: number; onAction: (a: NonNullable<InsightAction>) => void }) {
  const { cells, events } = useStore(); const [report, setReport] = useState(false);
  const rows = useMemo(() => getInsights(cells, events, now), [cells, events, now]);
  return (
    <div className="card flex flex-col p-5">
      <h2 className="flex items-center gap-2 text-[16px] font-semibold">Quick Insights
        <span title="Generated by simple rules over your own data, not an AI model" className="rounded-md bg-primary/20 px-1.5 py-0.5 text-[10px] font-bold text-primary">Auto</span></h2>
      <ul className="mt-3 divide-y divide-line">
        {rows.map((r) => { const I = ICON[r.key]; const Tag = r.action ? "button" : "div"; return (
          <li key={r.key}><Tag {...(r.action ? { onClick: () => onAction(r.action!) } : {})} className={`flex w-full items-center gap-3 py-3 text-left ${r.action ? "group rounded-lg hover:bg-white/5" : ""}`}>
            <span className="grid h-10 w-10 shrink-0 place-items-center rounded-xl" style={{ background: `${TONE[r.key]}26`, color: TONE[r.key] }}><I size={19} aria-hidden /></span>
            <span className="min-w-0 flex-1"><span className="block text-[11px] font-semibold text-mute">{r.label}</span><span className="block text-[13px] font-medium leading-snug">{r.text}</span></span>
            {r.action && <ChevronRight size={16} className="text-mute transition group-hover:translate-x-0.5" aria-hidden />}</Tag></li>); })}
      </ul>
      <button onClick={() => setReport(true)} className="btn-blue mt-auto flex items-center justify-center gap-2 px-4 py-2.5 text-[13px]">View Full Report <ArrowRight size={14} aria-hidden /></button>
      <AnimatePresence>{report && <Report now={now} onClose={() => setReport(false)} />}</AnimatePresence>
    </div>
  );
}

function Row({ k, v }: { k: string; v: number }) {
  return <li className="flex justify-between py-1.5 text-sm"><span className="capitalize text-mute">{k}</span><span className="font-semibold">{v}</span></li>;
}

function Report({ now, onClose }: { now: number; onClose: () => void }) {
  const { cells, events } = useStore();
  const d = useMemo(() => {
    const active = cells.filter((c) => !c.archived && !c.done);
    const by = (f: (c: typeof cells[number]) => string) => active.reduce<Record<string, number>>((o, c) => ((o[f(c)] = (o[f(c)] ?? 0) + 1), o), {});
    return { total: active.length, state: by((c) => getMomentum(c, now).state), kind: by((c) => c.kind), event: by((c) => events.find((e) => e.id === c.eventId)?.title ?? "No event"),
      done: cells.filter((c) => c.done).length, archived: cells.filter((c) => c.archived).length };
  }, [cells, events, now]);
  const download = () => {
    const blob = new Blob([JSON.stringify({ exportedAt: new Date().toISOString(), events, cells }, null, 2)], { type: "application/json" });
    const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = "event-bee-buzz-backup.json"; a.click(); URL.revokeObjectURL(a.href);
  };
  return (
    <motion.div className="fixed inset-0 z-50 grid place-items-center bg-black/60 p-4" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={onClose}>
      <motion.div role="dialog" aria-modal="true" aria-label="Full report" onClick={(e) => e.stopPropagation()} onKeyDown={(e) => e.key === "Escape" && onClose()}
        className="card max-h-[88dvh] w-full max-w-lg overflow-y-auto p-6" initial={{ y: 30, scale: 0.97 }} animate={{ y: 0, scale: 1 }} exit={{ y: 30 }}>
        <div className="flex items-center justify-between"><h2 className="text-xl font-semibold">Hive report</h2><button autoFocus onClick={onClose} aria-label="Close" className="rounded-full p-2 text-mute hover:bg-white/5"><X size={18} /></button></div>
        <p className="mt-1 text-sm text-mute">{d.total} active items, {d.done} done, {d.archived} archived.</p>
        <div className="mt-4 grid gap-5 sm:grid-cols-3">
          <section><h3 className="text-xs font-semibold uppercase tracking-wide text-honey">By state</h3><ul className="mt-1 divide-y divide-line">{(["hot", "warm", "cooling", "cold"] as MomentumState[]).map((s) => <Row key={s} k={STATE_LABEL[s]} v={d.state[s] ?? 0} />)}</ul></section>
          <section><h3 className="text-xs font-semibold uppercase tracking-wide text-honey">By type</h3><ul className="mt-1 divide-y divide-line">{Object.entries(d.kind).map(([k, v]) => <Row key={k} k={k} v={v} />)}</ul></section>
          <section><h3 className="text-xs font-semibold uppercase tracking-wide text-honey">By event</h3><ul className="mt-1 divide-y divide-line">{Object.entries(d.event).map(([k, v]) => <Row key={k} k={k} v={v} />)}</ul></section>
        </div>
        <p className="mt-5 text-xs text-mute">Your data lives only in this browser. Download a backup any time.</p>
        <button onClick={download} className="btn-gold mt-3 inline-flex items-center gap-2 px-4 py-2.5 text-sm"><Download size={16} aria-hidden /> Download JSON backup</button>
      </motion.div>
    </motion.div>
  );
}
